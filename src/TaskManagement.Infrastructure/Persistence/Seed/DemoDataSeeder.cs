using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using TaskManagement.Application.Common.Interfaces;
using TaskManagement.Domain.Entities;
using TaskManagement.Domain.Enums;

namespace TaskManagement.Infrastructure.Persistence.Seed;

// Fills the database with fake data so I can test paging/filtering and measure the list endpoints.
// Only runs when Seed:DemoData = true and there are no projects yet.
public class DemoDataSeeder
{
    public const string DemoPassword = "Password123!";

    private const int ManagerCount = 5;
    private const int MemberCount = 40;
    private const int ProjectCount = 30;
    private const int BatchSize = 2000;

    private static readonly string[] Verbs = ["Fix", "Add", "Update", "Refactor", "Test", "Review", "Document", "Deploy", "Design", "Investigate"];
    private static readonly string[] Things = ["login page", "payment flow", "search API", "user profile", "email templates", "dashboard", "CI pipeline", "error logging", "reports export", "mobile layout", "invoice PDF", "notifications"];

    private readonly AppDbContext _context;
    private readonly IPasswordHasher _passwordHasher;
    private readonly ILogger _logger;

    // fixed seed so every run generates the same data (makes measurements comparable)
    private readonly Random _random = new(42);

    public DemoDataSeeder(AppDbContext context, IPasswordHasher passwordHasher, ILogger logger)
    {
        _context = context;
        _passwordHasher = passwordHasher;
        _logger = logger;
    }

    public async Task SeedAsync(int taskCount, CancellationToken cancellationToken = default)
    {
        if (await _context.Projects.AnyAsync(cancellationToken))
            return;

        _logger.LogInformation("Seeding demo data with {TaskCount} tasks", taskCount);

        // hashing is slow on purpose (bcrypt), so hash once and reuse it for all demo users
        var passwordHash = _passwordHasher.Hash(DemoPassword);

        var managers = Enumerable.Range(1, ManagerCount)
            .Select(i => NewUser($"Manager {i}", $"manager{i}@demo.local", UserRole.Manager, passwordHash))
            .ToList();
        var members = Enumerable.Range(1, MemberCount)
            .Select(i => NewUser($"Member {i}", $"member{i}@demo.local", UserRole.Member, passwordHash))
            .ToList();

        _context.Users.AddRange(managers);
        _context.Users.AddRange(members);
        await _context.SaveChangesAsync(cancellationToken);

        var projects = new List<Project>();
        for (var i = 1; i <= ProjectCount; i++)
        {
            var owner = managers[(i - 1) % managers.Count];
            var project = new Project
            {
                Name = $"Project {i:D2}",
                Description = $"Demo project number {i}",
                OwnerId = owner.Id,
                CreatedAt = DateTime.UtcNow.AddDays(-_random.Next(30, 365))
            };

            project.Members.Add(new ProjectMember { UserId = owner.Id });
            foreach (var member in members.OrderBy(_ => _random.Next()).Take(_random.Next(5, 11)))
            {
                project.Members.Add(new ProjectMember { UserId = member.Id });
            }

            projects.Add(project);
        }

        _context.Projects.AddRange(projects);
        await _context.SaveChangesAsync(cancellationToken);

        var created = 0;
        while (created < taskCount)
        {
            var batch = new List<TaskItem>();
            for (var i = 0; i < BatchSize && created < taskCount; i++, created++)
            {
                batch.Add(NewTask(projects[_random.Next(projects.Count)]));
            }

            _context.Tasks.AddRange(batch);
            await _context.SaveChangesAsync(cancellationToken);

            // without this the change tracker keeps every inserted task and the seed gets slower and slower
            _context.ChangeTracker.Clear();
        }

        _logger.LogInformation("Demo data seeded: {ProjectCount} projects, {UserCount} users, {TaskCount} tasks",
            projects.Count, managers.Count + members.Count, created);
    }

    private static User NewUser(string name, string email, UserRole role, string passwordHash) => new()
    {
        FullName = name,
        Email = email,
        Role = role,
        PasswordHash = passwordHash
    };

    private TaskItem NewTask(Project project)
    {
        var memberIds = project.Members.Select(m => m.UserId).ToList();
        var createdAt = DateTime.UtcNow.AddDays(-_random.Next(0, 180)).AddMinutes(-_random.Next(0, 1440));

        var task = new TaskItem
        {
            ProjectId = project.Id,
            Title = $"{Verbs[_random.Next(Verbs.Length)]} {Things[_random.Next(Things.Length)]}",
            Description = "Generated by the demo data seeder.",
            Priority = (TaskPriority)_random.Next(0, 4),
            DueDate = _random.Next(0, 5) == 0 ? null : createdAt.Date.AddDays(_random.Next(1, 60)),
            // about 1 in 5 tasks has nobody assigned
            AssigneeId = _random.Next(0, 5) == 0 ? null : memberIds[_random.Next(memberIds.Count)],
            CreatedById = project.OwnerId,
            CreatedAt = createdAt
        };

        task.ChangeStatus((TaskItemStatus)_random.Next(0, 4));
        return task;
    }
}
